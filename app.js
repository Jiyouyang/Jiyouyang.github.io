const $ = selector => document.querySelector(selector);
const reader = $('#reader');
const settings = $('#settings');
const system = matchMedia('(prefers-color-scheme: dark)');
let category = 'all';
let currentPostId = null;
let preference = 'auto';
let accentPreference = 'graphite';
let language = 'zh-CN';

try {
  preference = localStorage.getItem('jy-theme') || 'auto';
  accentPreference = localStorage.getItem('jy-accent') || 'graphite';
  language = localStorage.getItem('jy-language') || 'zh-CN';
} catch {}
if (!i18n[language]) language = 'zh-CN';

const esc = value => value.replace(/[&<>"']/g, character => ({
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;'
})[character]);

const t = (key, variables = {}) => Object.entries(variables).reduce(
  (value, entry) => value.replaceAll('{' + entry[0] + '}', entry[1]),
  i18n[language][key] || i18n['zh-CN'][key] || key
);

const localized = post => post.content[language] || post.content['zh-CN'];
const readingTime = minutes => t('article.time', { n: String(minutes) });

function persist(key, value) {
  try { localStorage.setItem(key, value); } catch {}
}

function render() {
  const query = $('#search').value.trim().toLocaleLowerCase();
  const list = posts.filter(post => {
    const content = localized(post);
    const haystack = (content.title + ' ' + content.summary + ' ' + t('category.' + post.category)).toLocaleLowerCase();
    return (category === 'all' || post.category === category) && haystack.includes(query);
  });
  $('#count').textContent = t('journal.count', { n: String(list.length) });
  $('#posts').innerHTML = list.length ? list.map(post => {
    const content = localized(post);
    return '<button class="card" data-post="' + post.id + '" aria-label="' + esc(t('article.readLabel', { title: content.title })) + '">' +
      '<div class="visual ' + post.visual + '" aria-hidden="true"><span class="bigglyph">' + post.glyph + '</span></div>' +
      '<div class="card-body"><span class="tag">' + t('category.' + post.category) + ' · ' + t('article.note') + '</span>' +
      '<h3>' + content.title + '</h3><p>' + content.summary + '</p>' +
      '<div class="meta"><span>' + post.date + '</span><span>' + readingTime(post.minutes) + ' ↗</span></div></div></button>';
  }).join('') : '<p class="empty">' + t('journal.empty') + '</p>';
}

function updateBodyLock() {
  document.body.style.overflow = reader.open || settings.open ? 'hidden' : '';
}

function openPost(id) {
  const post = posts.find(item => item.id === id);
  if (!post) return;
  currentPostId = id;
  const content = localized(post);
  $('#article').innerHTML = '<span class="tag">' + t('category.' + post.category) + ' · ' + t('article.blogNote') + '</span>' +
    '<h1 id="article-title">' + content.title + '</h1>' +
    '<div class="meta"><span>' + post.date + '</span><span>' + readingTime(post.minutes) + '</span></div>' +
    content.body + '<button class="share" id="share">' + t('article.copy') + '</button>';
  if (!reader.open) reader.showModal();
  reader.scrollTop = 0;
  updateBodyLock();
  document.title = content.title + ' · Jiyouyang';
  $('#share').onclick = async () => {
    const url = new URL(location.href);
    url.hash = 'post/' + post.id;
    try {
      await navigator.clipboard.writeText(url.href);
      $('#share').textContent = t('article.copied');
    } catch {
      $('#share').textContent = t('article.copyFallback');
    }
  };
}

function route() {
  const match = location.hash.match(/^#post\/(.+)$/);
  if (match) {
    const post = posts.find(item => item.id === match[1]);
    if (post) openPost(post.id);
  } else if (reader.open) {
    reader.close();
  }
}

function applyAccent() {
  document.documentElement.dataset.accent = accentPreference;
  document.querySelectorAll('[data-accent-choice]').forEach(button => {
    const active = button.dataset.accentChoice === accentPreference;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  persist('jy-accent', accentPreference);
}

function applyTheme() {
  document.documentElement.dataset.theme = preference === 'auto'
    ? (system.matches ? 'dark' : 'light')
    : preference;
  $('meta[name="theme-color"]').content = document.documentElement.dataset.theme === 'dark' ? '#000000' : '#f5f5f7';
  const buttons = [...document.querySelectorAll('[data-mode]')];
  const index = Math.max(0, buttons.findIndex(button => button.dataset.mode === preference));
  $('.mode-switch').style.setProperty('--active-index', index);
  buttons.forEach((button, buttonIndex) => {
    button.classList.toggle('active', buttonIndex === index);
    button.setAttribute('aria-pressed', String(buttonIndex === index));
  });
  persist('jy-theme', preference);
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-label]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nLabel));
  });
  $('meta[name="description"]').content = t('meta.description');
  $('#featured-time').textContent = readingTime(3);
  const buttons = [...document.querySelectorAll('[data-language]')];
  const index = Math.max(0, buttons.findIndex(button => button.dataset.language === language));
  $('.language-switch').style.setProperty('--active-index', index);
  buttons.forEach((button, buttonIndex) => {
    button.classList.toggle('active', buttonIndex === index);
    button.setAttribute('aria-pressed', String(buttonIndex === index));
  });
  render();
  if (reader.open && currentPostId) {
    openPost(currentPostId);
  } else {
    document.title = t('meta.title');
  }
  persist('jy-language', language);
}

document.addEventListener('click', event => {
  const button = event.target.closest('[data-post]');
  if (!button) return;
  const hash = '#post/' + button.dataset.post;
  if (location.hash === hash) openPost(button.dataset.post);
  else location.hash = hash;
});

$('#close-reader').onclick = () => reader.close();
reader.addEventListener('click', event => {
  const bounds = reader.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) reader.close();
});
reader.addEventListener('close', () => {
  currentPostId = null;
  updateBodyLock();
  document.title = t('meta.title');
  if (location.hash.startsWith('#post/')) history.replaceState(null, '', location.pathname + location.search + '#journal');
});

document.querySelectorAll('[data-category]').forEach(button => {
  button.onclick = () => {
    category = button.dataset.category;
    document.querySelectorAll('[data-category]').forEach(item => {
      item.classList.toggle('active', item === button);
      item.setAttribute('aria-pressed', String(item === button));
    });
    render();
  };
});

