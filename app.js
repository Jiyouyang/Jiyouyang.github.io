const navSlider = $('.navlinks');
const navItems = [...document.querySelectorAll('.navlinks a')];
function activateNav(index) {
  navSlider.style.setProperty('--active-index', index);
  navItems.forEach((item, itemIndex) => {
    item.classList.toggle('active', itemIndex === index);
    if (itemIndex === index) item.setAttribute('aria-current', 'page');
    else item.removeAttribute('aria-current');
  });
}
navItems.forEach((item, index) => item.addEventListener('click', () => activateNav(index)));
function syncNav() {
  activateNav(scrollY + innerHeight * 0.36 >= $('#resources').offsetTop ? 1 : 0);
}
addEventListener('scroll', syncNav, { passive: true });
addEventListener('resize', syncNav);

