const $ = selector => document.querySelector(selector);
const settings = $('#settings');
const systemTheme = matchMedia('(prefers-color-scheme: dark)');
let category = 'all';
let preference = 'auto';
let accentPreference = 'graphite';
let language = 'zh-CN';

try {
  preference = localStorage.getItem('jy-theme') || 'auto';
  accentPreference = localStorage.getItem('jy-accent') || 'graphite';
  language = localStorage.getItem('jy-language') || 'zh-CN';
} catch {}
if (!i18n[language]) language = 'zh-CN';

const escapeHtml = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
})[character]);
const t = (key, variables = {}) => Object.entries(variables).reduce(
  (value, [name, replacement]) => value.replaceAll('{' + name + '}', replacement),
  i18n[language][key] || i18n['zh-CN'][key] || key
);
const localized = resource => resource.content[language] || resource.content['zh-CN'];
const persist = (key, value) => { try { localStorage.setItem(key, value); } catch {} };

function renderResources() {
  const query = $('#search').value.trim().toLocaleLowerCase();
  const list = resources.filter(resource => {
    const [title, description] = localized(resource);
    const haystack = (title + ' ' + description + ' ' + resource.domain + ' ' + t('category.' + resource.category)).toLocaleLowerCase();
    return (category === 'all' || resource.category === category) && haystack.includes(query);
  });
  $('#count').textContent = t('library.count', { n: String(list.length) });
  $('#resource-grid').innerHTML = list.length ? list.map(resource => {
    const [title, description] = localized(resource);
    return '<a class="resource-card" href="' + resource.url + '" target="_blank" rel="noopener noreferrer" aria-label="' + escapeHtml(t('resource.open', { title })) + '">' +
      '<div class="resource-visual" style="--x:' + resource.x + ';--y:' + resource.y + '"><span class="resource-glyph">' + escapeHtml(resource.glyph) + '</span></div>' +
      '<div class="resource-body"><div class="resource-topline"><span class="resource-tag">' + escapeHtml(t('category.' + resource.category)) + '</span><span class="resource-arrow">↗</span></div>' +
      '<h3>' + escapeHtml(title) + '</h3><p>' + escapeHtml(description) + '</p><div class="resource-domain">' + escapeHtml(resource.domain) + '</div></div></a>';
  }).join('') : '<p class="empty">' + escapeHtml(t('library.empty')) + '</p>';
}

function applyAccent() {
  document.documentElement.dataset.accent = accentPreference;
  document.querySelectorAll('[data-accent-choice]').forEach(button => {
    const active = button.dataset.accentChoice === accentPreference;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  persist('jy-accent', accentPreference);
}

function applyTheme() {
  document.documentElement.dataset.theme = preference === 'auto' ? (systemTheme.matches ? 'dark' : 'light') : preference;
  $('meta[name="theme-color"]').content = document.documentElement.dataset.theme === 'dark' ? '#000000' : '#f5f5f7';
  const buttons = [...document.querySelectorAll('[data-mode]')];
  const index = Math.max(0, buttons.findIndex(button => button.dataset.mode === preference));
  $('.mode-switch').style.setProperty('--active-index', index);
  buttons.forEach((button, buttonIndex) => {
    button.classList.toggle('active', buttonIndex === index);
    button.setAttribute('aria-pressed', String(buttonIndex === index));
  });
  persist('jy-theme', preference);
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(element => { element.innerHTML = t(element.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-label]').forEach(element => { element.setAttribute('aria-label', t(element.dataset.i18nLabel)); });
  document.title = t('meta.title');
  $('meta[name="description"]').content = t('meta.description');
  const buttons = [...document.querySelectorAll('[data-language]')];
  const index = Math.max(0, buttons.findIndex(button => button.dataset.language === language));
  $('.language-switch').style.setProperty('--active-index', index);
  buttons.forEach((button, buttonIndex) => {
    button.classList.toggle('active', buttonIndex === index);
    button.setAttribute('aria-pressed', String(buttonIndex === index));
  });
  renderResources();
  persist('jy-language', language);
}

document.querySelectorAll('[data-category]').forEach(button => {
  button.onclick = () => {
    category = button.dataset.category;
    document.querySelectorAll('[data-category]').forEach(item => {
      item.classList.toggle('active', item === button);
      item.setAttribute('aria-pressed', String(item === button));
    });
    renderResources();
  };
});

$('#search').oninput = renderResources;
$('#search-jump').onclick = () => {
  const input = $('#search');
  const searchBox = input.closest('.search');
  const targetTop = Math.max(0, scrollY + searchBox.getBoundingClientRect().top - (innerWidth <= 590 ? 188 : 140));
  history.replaceState(null, '', location.pathname + location.search + '#resources');
  input.focus({ preventScroll: true });
  window.scrollTo({ top: targetTop, behavior: 'smooth' });
};

$('#settings-trigger').onclick = () => {
  settings.showModal();
  document.body.style.overflow = 'hidden';
};
$('#close-settings').onclick = () => settings.close();
settings.addEventListener('click', event => {
  const bounds = settings.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) settings.close();
});
settings.addEventListener('close', () => { document.body.style.overflow = ''; });

document.querySelectorAll('[data-accent-choice]').forEach(button => {
  button.onclick = () => { accentPreference = button.dataset.accentChoice; applyAccent(); };
});
document.querySelectorAll('[data-mode]').forEach(button => {
  button.onclick = () => { preference = button.dataset.mode; applyTheme(); };
});
document.querySelectorAll('[data-language]').forEach(button => {
  button.onclick = () => { language = button.dataset.language; applyLanguage(); };
});

systemTheme.addEventListener('change', () => { if (preference === 'auto') applyTheme(); });
$('#year').textContent = new Date().getFullYear();
$('#resource-total').textContent = String(resources.length);
applyAccent();
